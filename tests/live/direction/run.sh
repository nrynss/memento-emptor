#!/usr/bin/env bash
# T2.7b live driver: re-prove the direction rule against a real Lambo.
#
# Usage:
#   source tools/env.sh
#   EMBEDDER=native LAMBO_BIN=$HOME/work/lambo/target/release/lambo \
#     bash tests/live/direction/run.sh
#
# EMBEDDER picks the [embedder] section the run seeds through:
#   native  kind=elastic on .jina-embeddings-v3 (T0.6b shape, 0.10.1 timeout
#           knobs against the DNS stall); needs ELASTIC_URL + LAMBO_ES_API_KEY
#   bge_m3  the settled T0.6 contract via OpenRouter; needs OPENROUTER_API_KEY
#   fixture the T0.3 local-only contract; needs no key (mechanics fallback)
#
# A native run first probes the embedder in a scratch session: when the
# probe reports the embedder down, the script stops before seeding and the
# operator reruns with EMBEDDER=bge_m3. Nothing is committed by this
# script: the store, the config (which carries the deployment URL) and the
# raw transcript stay under out/ (gitignored). After the checks pass the
# throwaway session is erased and the run verifies no indices remain.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="${OUT:-$HERE/out}"
SESSION="${SESSION:-t27b-direction}"
T27B_AGENT="${T27B_AGENT:-memento-t27b}"
EMBEDDER="${EMBEDDER:-native}"
LAMBO_BIN="${LAMBO_BIN:-$HOME/work/lambo/target/release/lambo}"

mkdir -p "$OUT"
"$LAMBO_BIN" --version

write_config() {
	local dir="$1" kind="$2"
	{
		echo "# T2.7b live run config, generated by run.sh (not committed)."
		echo "[store]"
		echo "kind = \"sqlite\""
		echo "path = \"$dir/lambo.db\""
		echo ""
		echo "[embedder]"
		case "$kind" in
		native)
			: "${ELASTIC_URL:?EMBEDDER=native needs ELASTIC_URL from tools/env.sh}"
			: "${LAMBO_ES_API_KEY:?EMBEDDER=native needs LAMBO_ES_API_KEY from tools/env.sh}"
			echo "kind = \"elastic\""
			echo "url = \"$ELASTIC_URL\""
			echo "model = \".jina-embeddings-v3\""
			echo "dim = 1024"
			echo "api_key_env = \"LAMBO_ES_API_KEY\""
			echo "connect_timeout_ms = 30000"
			echo "timeout_ms = 60000"
			echo "canary = \"verify\""
			;;
		bge_m3)
			: "${OPENROUTER_API_KEY:?EMBEDDER=bge_m3 needs OPENROUTER_API_KEY from tools/env.sh}"
			echo "kind = \"bge_m3\""
			echo "url = \"https://openrouter.ai/api\""
			echo "model = \"baai/bge-m3\""
			echo "dim = 1024"
			echo "api_key_env = \"OPENROUTER_API_KEY\""
			;;
		fixture)
			echo "kind = \"fixture\""
			echo "dim = 1024"
			echo "calibration = \"off\""
			;;
		esac
		echo ""
		echo "# Cadence only, from the proven T0.3 toml; the bars live in code."
		echo "[daemon]"
		echo "gc_interval = 1"
		echo "gc_idle_floor = 1"
		echo "gc_max_interval_secs = 3600"
		echo "canonization_eval_interval_secs = 5"
	} >"$dir/lambo.toml"
}

if [ "$EMBEDDER" = "native" ]; then
	echo "--- native embedder probe (scratch session) ---"
	mkdir -p "$OUT/probe"
	write_config "$OUT/probe" native
	"$LAMBO_BIN" --config "$OUT/probe/lambo.toml" provision
	# drive.py owns the writer's stdio pipes, so it starts serve itself.
	if ! python3 "$HERE/drive.py" --lambo "$LAMBO_BIN" \
		--config "$OUT/probe/lambo.toml" --session t27b-probe \
		--agent "$T27B_AGENT" --out "$OUT/probe" --probe; then
		echo "native embedder unreachable from this network; rerun with EMBEDDER=bge_m3"
		exit 3
	fi
	# Probe passed: drop the scratch store and seed for real.
	rm -rf "$OUT/probe"
fi

echo "--- seeding t27b-direction through embedder=$EMBEDDER ---"
mkdir -p "$OUT/run"
write_config "$OUT/run" "$EMBEDDER"
"$LAMBO_BIN" --config "$OUT/run/lambo.toml" provision
: >"$OUT/run/transcript.jsonl"

python3 "$HERE/drive.py" --lambo "$LAMBO_BIN" \
	--config "$OUT/run/lambo.toml" --session "$SESSION" \
	--agent "$T27B_AGENT" --out "$OUT/run"

echo "--- cleanup: erase the throwaway session ---"
"$LAMBO_BIN" --config "$OUT/run/lambo.toml" erase-session \
	--session "$SESSION" --confirm "$SESSION" | tee "$OUT/run/erase.txt"
if "$LAMBO_BIN" --config "$OUT/run/lambo.toml" inspect \
	--session "$SESSION" \
	--focus "Brand X oxford runs small for this shopper: take size L" \
	>"$OUT/run/inspect-after-erase.txt" 2>&1; then
	echo "UNEXPECTED: inspect succeeded after erase"
	exit 1
else
	echo "session is gone (inspect refuses after erase, see out/run/inspect-after-erase.txt)"
fi

if [ "$EMBEDDER" = "native" ]; then
	echo "--- verify no indices remain ---"
	: "${ELASTIC_URL:?EMBEDDER=native needs ELASTIC_URL from tools/env.sh}"
	: "${LAMBO_ES_API_KEY:?EMBEDDER=native needs LAMBO_ES_API_KEY from tools/env.sh}"
	curl -s -m 30 -H "Authorization: ApiKey $LAMBO_ES_API_KEY" \
		"$ELASTIC_URL/_cat/indices/t27b*?format=json&h=index" | tee "$OUT/run/indices-after.txt"
	echo ""
fi

echo "--- leak check: no secret value entered tests/live/direction ---"
leaks=""
for value in "${ELASTIC_URL:-}" "${LAMBO_ES_API_KEY:-}" "${OPENROUTER_API_KEY:-}"; do
	[ -n "$value" ] || continue
	found=$(grep -rlF --exclude-dir=out -- "$value" "$HERE" || true)
	[ -z "$found" ] || leaks="${leaks}${found}"$'\n'
done
if [ -n "$leaks" ]; then
	echo "secret value entered a file:" >&2
	printf '%s' "$leaks" >&2
	exit 1
fi
# The deployment URL is a locator, not a secret, but it still stays
# out of the repo: the generated config lives under out/ only.
if [ -n "${ELASTIC_URL:-}" ]; then
	found=$(grep -rlF --exclude-dir=out -- "$ELASTIC_URL" "$HERE" || true)
	if [ -n "$found" ]; then
		echo "deployment URL entered a committed file:" >&2
		printf '%s' "$found" >&2
		exit 1
	fi
fi

# The full transcript must stay out of git.
git check-ignore -q "$HERE/out"

echo "done: T2.7b live checks pass; session erased; transcript under $OUT/run (git-ignored)"

#!/usr/bin/env bash
# T2.8b live run: the rival-birth rule against a real Lambo.
#
# Usage:
#   source tools/env.sh
#   LAMBO_BIN=$HOME/work/lambo/target/release/lambo \
#     bash tests/live/rival/run.sh
#
# Native embedder only (T0.6b shape, 0.10.1 timeout knobs against the DNS
# stall): needs ELASTIC_URL + LAMBO_ES_API_KEY. When the embedder is
# down, the run fails on the first receipt wait instead of seeding;
# there is no fallback embedder on this task. Nothing is committed by
# this script: the store, the config (which carries the deployment URL)
# and the raw inspect excerpts stay under out/ (gitignored). After the
# checks pass the throwaway session is erased and the run verifies no
# indices remain.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="${OUT:-$HERE/out}"
LAMBO_BIN="${LAMBO_BIN:-$HOME/work/lambo/target/release/lambo}"

mkdir -p "$OUT"
"$LAMBO_BIN" --version

{
	echo "# T2.8b live run config, generated by run.sh (not committed)."
	echo "[store]"
	echo "kind = \"sqlite\""
	echo "path = \"$OUT/lambo.db\""
	echo ""
	echo "[embedder]"
	: "${ELASTIC_URL:?EMBEDDER=native needs ELASTIC_URL from tools/env.sh}"
	: "${LAMBO_ES_API_KEY:?EMBEDDER=native needs LAMBO_ES_API_KEY from tools/env.sh}"
	echo "kind = \"elastic\""
	echo "url = \"$ELASTIC_URL\""
	echo "model = \".jina-embeddings-v3\""
	echo "dim = 1024"
	echo "api_key_env = \"LAMBO_ES_API_KEY\""
	echo "connect_timeout_ms = 30000"
	echo "timeout_ms = 60000"
	echo "canary = \"verify\""
	echo ""
	echo "# Cadence only, from the proven T0.3 toml; the bars live in code."
	echo "[daemon]"
	echo "gc_interval = 1"
	echo "gc_idle_floor = 1"
	echo "gc_max_interval_secs = 3600"
	echo "canonization_eval_interval_secs = 5"
} >"$OUT/lambo.toml"

echo "--- provisioning the store ---"
"$LAMBO_BIN" --config "$OUT/lambo.toml" provision

echo "--- driving the rival rule through the frozen service on live Lambo ---"
export LAMBO_BIN OUT
export LAMBO_CFG="$OUT/lambo.toml"
: >"$OUT/driver.log"
# One case per session: belief contents carry no shopper id, so the
# two cases would share concepts in one session and the interrupted
# case could never prove absence.
for CASE in birth gap; do
	SESSION="t28b-rival-$CASE"
	export CASE SESSION
	echo "=== case $CASE in session $SESSION ===" | tee -a "$OUT/driver.log"
	go run ./tests/live/rival 2>&1 | tee -a "$OUT/driver.log"
done

echo "--- cleanup: erase both throwaway sessions ---"
for CASE in birth gap; do
	SESSION="t28b-rival-$CASE"
	"$LAMBO_BIN" --config "$OUT/lambo.toml" erase-session \
		--session "$SESSION" --confirm "$SESSION" | tee "$OUT/erase-$CASE.txt"
done
if "$LAMBO_BIN" --config "$OUT/lambo.toml" inspect \
	--session "t28b-rival-birth" \
	--focus "memento fit brand brand-x-001 runs small, take size L" \
	>"$OUT/inspect-after-erase.txt" 2>&1; then
	echo "UNEXPECTED: inspect succeeded after erase"
	exit 1
else
	echo "sessions are gone (inspect refuses after erase, see out/inspect-after-erase.txt)"
fi

echo "--- verify no indices remain ---"
: "${ELASTIC_URL:?needs ELASTIC_URL from tools/env.sh}"
: "${LAMBO_ES_API_KEY:?needs LAMBO_ES_API_KEY from tools/env.sh}"
curl -s -m 30 -H "Authorization: ApiKey $LAMBO_ES_API_KEY" \
	"$ELASTIC_URL/_cat/indices/t28b*?format=json&h=index" | tee "$OUT/indices-after.txt"
echo ""

echo "--- leak check: no secret value entered tests/live/rival ---"
leaks=""
for value in "${ELASTIC_URL:-}" "${LAMBO_ES_API_KEY:-}" "${OPENROUTER_API_KEY:-}"; do
	[ -n "$value" ] || continue
	found=$(grep -rlF --exclude-dir=out -- "$value" "$HERE" || true)
	[ -z "$found" ] || leaks="${leaks}${found}"$'\n'
done
if [ -n "$leaks" ]; then
	echo "secret value entered a file:" >&2
	printf '%s' "$leaks" >&2
	exit 1
fi
# The deployment URL is a locator, not a secret, but it still stays
# out of the repo: the generated config lives under out/ only.
if [ -n "${ELASTIC_URL:-}" ]; then
	found=$(grep -rlF --exclude-dir=out -- "$ELASTIC_URL" "$HERE" || true)
	if [ -n "$found" ]; then
		echo "deployment URL entered a committed file:" >&2
		printf '%s' "$found" >&2
		exit 1
	fi
fi

# The full transcript must stay out of git.
git check-ignore -q "$HERE/out"

echo "done: T2.8b live checks pass; session erased; excerpts under $OUT (git-ignored)"
